----------------PHASE 2: POPULATE THE DENORMALIZED TABLE------------------

--POPULATE DIM_DATE TABLE
TRUNCATE TABLE PARIS_IMMO.DENORM.DIM_DATE;

INSERT INTO PARIS_IMMO.DENORM.DIM_DATE
WITH DATES AS (
    SELECT DATEADD(DAY, SEQ4(), '2020-01-01'::DATE) AS D
    FROM TABLE(GENERATOR(ROWCOUNT => 4018))
)
SELECT
    D                                     AS DATE_ID,
    YEAR(D)                               AS YEAR,
    QUARTER(D)                            AS QUARTER,
    MONTH(D)                              AS MONTH,
    TO_CHAR(D, 'MONTH')                   AS MONTH_NAME,
    DAY(D)                                AS DAY,
    DAYOFWEEK(D)                          AS DAY_OF_WEEK,
    TO_CHAR(D, 'DAY')                     AS DAY_NAME
FROM DATES
WHERE D <= '2025-12-31'::DATE;




--POPULATE DIM_GEOGRAPHY TABLE
TRUNCATE TABLE PARIS_IMMO.DENORM.DIM_GEOGRAPHY;

INSERT INTO PARIS_IMMO.DENORM.DIM_GEOGRAPHY
SELECT
    N.NEIGHBOURHOOD_ID,
    N.NEIGHBOURHOOD_NAME,
    A.ARRONDISSEMENT_CODE,
    A.ARRONDISSEMENT_NAME,
    N.CENTROID_LAT,
    N.CENTROID_LON,
    N.GEOMETRY_WKT
FROM PARIS_IMMO.NORMALIZED.DIM_NEIGHBOURHOOD N
JOIN PARIS_IMMO.NORMALIZED.DIM_ARRONDISSEMENT A
    ON N.ARRONDISSEMENT_CODE = A.ARRONDISSEMENT_CODE;



--POPULATE DIM_PERMIT TABLE
TRUNCATE TABLE PARIS_IMMO.DENORM.DIM_PERMIT;

INSERT INTO PARIS_IMMO.DENORM.DIM_PERMIT
SELECT
	ROW_NUMBER() OVER (ORDER BY P.PERMIT_TYPE, PR.PROJECT_TYPE) AS PERMIT_SK,
	P.PERMIT_TYPE,
	P.PERMIT_TYPE_LABEL,
	PR.PROJECT_TYPE,
	PR.PROJECT_TYPE_LABEL,
	P.PERMIT_TYPE_LABEL || ' - ' || PR.PROJECT_TYPE_LABEL
FROM
	(SELECT DISTINCT PERMIT_TYPE, PERMIT_TYPE_LABEL FROM PARIS_IMMO.NORMALIZED.PERMIT_TYPE_LOOKUP) P
CROSS JOIN
	(SELECT DISTINCT PROJECT_TYPE, PROJECT_TYPE_LABEL FROM PARIS_IMMO.NORMALIZED.PROJECT_TYPE_LOOKUP) PR;


--POPULATE FACT_RENT
TRUNCATE TABLE PARIS_IMMO.DENORM.FACT_RENT_CONTROL;
INSERT INTO PARIS_IMMO.DENORM.FACT_RENT_CONTROL
SELECT
    R.RENT_ID,

    R.NEIGHBOURHOOD_ID,
    N.NEIGHBOURHOOD_NAME,
    N.ARRONDISSEMENT_CODE,
   

    R.YEAR,
    R.NB_ROOMS,

    C.CONSTRUCTION_PERIOD_LABEL AS CONSTRUCTION_PERIOD,
    F.FURNISHED_STATUS_LABEL AS FURNISHED_STATUS,

    R.RENT_REF,
    R.RENT_REF_UPPER,
    R.RENT_REF_LOWER

FROM PARIS_IMMO.NORMALIZED.FACT_RENT R

LEFT JOIN PARIS_IMMO.NORMALIZED.DIM_NEIGHBOURHOOD N
    ON R.NEIGHBOURHOOD_ID = N.NEIGHBOURHOOD_ID

LEFT JOIN PARIS_IMMO.NORMALIZED.DIM_CONSTRUCTION_PERIOD C
    ON R.CONSTRUCTION_PERIOD_ID = C.CONSTRUCTION_PERIOD_ID

LEFT JOIN PARIS_IMMO.NORMALIZED.DIM_FURNISHED_STATUS F
    ON R.FURNISHED_STATUS_ID = F.FURNISHED_STATUS_ID;

--POPULATE FACT_PERMIT_UNIFIED TABLE

