--POPULATE EVENT-LEVEL TABLE
TRUNCATE TABLE PARIS_IMMO.DENORM.FACT_COMPANY_EVENT;

INSERT INTO PARIS_IMMO.DENORM.FACT_COMPANY_EVENT
SELECT
    F.ESTABLISHMENT_ID,
    F.ESTABLISHMENT_CREATION_DATE,
    F.YEAR,
    F.ARRONDISSEMENT_CODE,
    A.ACTIVITY_LABEL ,
    F.EMPLOYEE_SIZE_BRACKET,
    F.ADMINISTRATIVE_STATUS
FROM PARIS_IMMO.NORMALIZED.FACT_COMPANY_ACTIVITY F
JOIN PARIS_IMMO.NORMALIZED.DIM_ACTIVITY A 
    ON F.MAIN_ACTIVITY_CODE = A.MAIN_ACTIVITY_CODE
;


--POPULATE ACTIVITY YEARLY
TRUNCATE TABLE PARIS_IMMO.DENORM.FACT_COMPANY_ACTIVITY_YEARLY;

INSERT INTO PARIS_IMMO.DENORM.FACT_COMPANY_ACTIVITY_YEARLY
SELECT
    F.ARRONDISSEMENT_CODE,
    F.YEAR,
    A.ACTIVITY_LABEL,

    /* Total establishments */
    COUNT(DISTINCT F.ESTABLISHMENT_ID) AS ESTABLISHMENTS_COUNT,

    /* Active establishments */
    COUNT(DISTINCT CASE 
        WHEN F.ADMINISTRATIVE_STATUS = 'Active' 
        THEN F.ESTABLISHMENT_ID 
    END) AS ACTIVE_ESTABLISHMENTS,

    /* Closed establishments (based on status, not YEAR_CLOSED) */
    COUNT(DISTINCT CASE 
        WHEN F.ADMINISTRATIVE_STATUS = 'Closed' 
        THEN F.ESTABLISHMENT_ID 
    END) AS CLOSED_ESTABLISHMENTS

FROM PARIS_IMMO.NORMALIZED.FACT_COMPANY_ACTIVITY F
JOIN PARIS_IMMO.NORMALIZED.DIM_ACTIVITY A 
    ON F.MAIN_ACTIVITY_CODE = A.MAIN_ACTIVITY_CODE

GROUP BY
    F.ARRONDISSEMENT_CODE,
    F.YEAR,
    A.ACTIVITY_LABEL;



