    -- FACT_TRANSACTION
    TRUNCATE TABLE PARIS_IMMO.NORMALIZED.FACT_TRANSACTION;

INSERT INTO PARIS_IMMO.NORMALIZED.FACT_TRANSACTION
    (TRANSACTION_ID,
     TRANSACTION_DATE,
     ARRONDISSEMENT_CODE,
     YEAR,
     TOTAL_BUILT_AREA,
     NB_ROOMS,
     PROPERTY_VALUE,
     LATITUDE,
     LONGITUDE)
WITH RAW AS (
    SELECT *
    FROM PARIS_IMMO.RAW.DVF_RAW
    WHERE NATURE_MUTATION = 'Vente'
      AND TRY_CAST(VALEUR_FONCIERE AS FLOAT) > 0
      AND CODE_DEPARTEMENT = '75'
),
INDICATORS AS (
    SELECT *,
        CASE WHEN TYPE_LOCAL = 'Maison' THEN 1 ELSE 0 END AS IS_MAISON,
        CASE WHEN TYPE_LOCAL = 'Appartement' THEN 1 ELSE 0 END AS IS_APPARTEMENT,
        CASE WHEN TYPE_LOCAL = 'Dépendance' THEN 1 ELSE 0 END AS IS_DEPENDANCE,
        CASE WHEN TYPE_LOCAL = 'Local industriel. commercial ou assimilé'
             THEN 1 ELSE 0 END AS IS_LOCAL_INDUSTRIEL,
        CASE WHEN TYPE_LOCAL IN ('Maison','Appartement',
                                 'Local industriel. commercial ou assimilé')
             THEN TRY_CAST(SURFACE_REELLE_BATI AS FLOAT)
             ELSE NULL END AS SURFACE_BATI_FOR_AGG
    FROM RAW
),
AGG AS (
    SELECT
        ID_MUTATION,
        MAX(TRY_TO_DATE(DATE_MUTATION)) AS TRANSACTION_DATE,
        MAX(TRY_CAST(VALEUR_FONCIERE AS FLOAT)) AS PROPERTY_VALUE,
        SUM(COALESCE(SURFACE_BATI_FOR_AGG, 0)) AS TOTAL_BUILT_AREA,
        SUM(TRY_CAST(NOMBRE_PIECES_PRINCIPALES AS INT)) AS NB_ROOMS,
        SUM(IS_MAISON) AS NB_MAISONS,
        SUM(IS_APPARTEMENT) AS NB_APPARTEMENTS,
        SUM(IS_DEPENDANCE) AS NB_DEPENDANCES,
        SUM(IS_LOCAL_INDUSTRIEL) AS NB_LOCAUX_INDUSTRIELS,
        MAX(CODE_COMMUNE) AS CODE_COMMUNE,
        MAX(LATITUDE) AS LATITUDE,
        MAX(LONGITUDE) AS LONGITUDE
    FROM INDICATORS
    GROUP BY ID_MUTATION
),
WITH_ARR AS (
    SELECT *,
        CASE
            WHEN LEFT(CODE_COMMUNE, 2) = '75'
             AND LENGTH(CODE_COMMUNE) = 5
            THEN TRY_CAST('751' || LPAD(RIGHT(CODE_COMMUNE, 2), 2, '0') AS INT)
            ELSE NULL
        END AS ARRONDISSEMENT_CODE,
        YEAR(TRANSACTION_DATE) AS YEAR
    FROM AGG
),
FILTERED AS (
    SELECT *
    FROM WITH_ARR
    WHERE TOTAL_BUILT_AREA > 0
      AND NB_DEPENDANCES = 0
      AND NB_APPARTEMENTS = 1
      AND NB_MAISONS = 0
      AND NB_LOCAUX_INDUSTRIELS = 0
      AND ARRONDISSEMENT_CODE IS NOT NULL
      AND YEAR BETWEEN 2020 AND 2025
)
SELECT
    ID_MUTATION,
    TRANSACTION_DATE,
    ARRONDISSEMENT_CODE,
    YEAR,
    TOTAL_BUILT_AREA,
    CAST(NB_ROOMS AS INT),
    PROPERTY_VALUE,
    TRY_CAST(LATITUDE AS FLOAT),
    TRY_CAST(LONGITUDE AS FLOAT)
FROM FILTERED
WHERE ID_MUTATION IS NOT NULL;


--FACT_RENT


TRUNCATE TABLE PARIS_IMMO.NORMALIZED.FACT_RENT;

INSERT INTO PARIS_IMMO.NORMALIZED.FACT_RENT
SELECT
    MD5(CONCAT_WS('|',
        R.CODE_GRAND_QUARTIER,
        R.ANNEE,
        R.PIECE,
        R.EPOQUE_CONSTRUCTION,
        R.TYPE_LOCATION
    )) AS RENT_ID,

    TRY_CAST(R.CODE_GRAND_QUARTIER AS NUMBER(38,0)) AS NEIGHBOURHOOD_ID,
    TRY_CAST(R.ANNEE AS NUMBER(38,0)) AS YEAR,
    TRY_CAST(R.PIECE AS NUMBER(38,0)) AS NB_ROOMS,

    C.CONSTRUCTION_PERIOD_ID,
    F.FURNISHED_STATUS_ID,

    TRY_CAST(R.REF AS FLOAT) AS RENT_REF,
    TRY_CAST(R.MAX AS FLOAT) AS RENT_REF_UPPER,
    TRY_CAST(R.MIN AS FLOAT) AS RENT_REF_LOWER

FROM PARIS_IMMO.RAW.RENT_RAW R

LEFT JOIN PARIS_IMMO.NORMALIZED.DIM_CONSTRUCTION_PERIOD C
    ON R.EPOQUE_CONSTRUCTION = C.CONSTRUCTION_PERIOD_LABEL

LEFT JOIN PARIS_IMMO.NORMALIZED.DIM_FURNISHED_STATUS F
    ON CASE
        WHEN LOWER(R.TYPE_LOCATION) = 'meublé' THEN 'FURNISHED'
        WHEN LOWER(R.TYPE_LOCATION) = 'non meublé' THEN 'UNFURNISHED'
        ELSE R.TYPE_LOCATION
    END = F.FURNISHED_STATUS_LABEL

WHERE R.CODE_GRAND_QUARTIER IS NOT NULL
  AND R.ANNEE IS NOT NULL
  AND R.PIECE IS NOT NULL
  AND TRY_CAST(R.ANNEE AS INT) BETWEEN 2020 AND 2025;



