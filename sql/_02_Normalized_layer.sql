-- DIM_YEAR
TRUNCATE TABLE PARIS_IMMO.NORMALIZED.DIM_YEAR;
INSERT INTO PARIS_IMMO.NORMALIZED.DIM_YEAR
SELECT DISTINCT YEAR(TRY_TO_DATE(date_mutation)) AS yr
FROM   PARIS_IMMO.RAW.DVF_RAW
WHERE  date_mutation IS NOT NULL
  AND  YEAR(TRY_TO_DATE(date_mutation)) BETWEEN 2020 AND 2025;

-- DIM_ARRONDISSEMENT

TRUNCATE TABLE PARIS_IMMO.NORMALIZED.DIM_ARRONDISSEMENT;

INSERT INTO PARIS_IMMO.NORMALIZED.DIM_ARRONDISSEMENT
    (ARRONDISSEMENT_CODE, ARRONDISSEMENT_NAME)
SELECT DISTINCT
    TRY_CAST(COM_ARM_CODE AS INT) AS ARRONDISSEMENT_CODE,
    COM_ARM_NAME AS ARRONDISSEMENT_NAME
FROM PARIS_IMMO.RAW.POPULATION_RAW
WHERE COM_ARM_CODE IS NOT NULL
  AND COM_ARM_NAME IS NOT NULL
  AND DEP_CODE = '75'
ORDER BY ARRONDISSEMENT_CODE;

-- DIM_NEIGHBOURHOOD
TRUNCATE TABLE PARIS_IMMO.NORMALIZED.DIM_NEIGHBOURHOOD;

INSERT INTO PARIS_IMMO.NORMALIZED.DIM_NEIGHBOURHOOD
    (NEIGHBOURHOOD_ID,
     ARRONDISSEMENT_CODE,
     NEIGHBOURHOOD_NAME,
     CENTROID_LAT,
     CENTROID_LON,
     GEOMETRY_WKT)
SELECT DISTINCT
    TRY_CAST(CODE_GRAND_QUARTIER AS INT) AS NEIGHBOURHOOD_ID,
    TRY_CAST(LEFT(CODE_GRAND_QUARTIER, 5) AS INT) AS ARRONDISSEMENT_CODE,
    NOM_QUARTIER AS NEIGHBOURHOOD_NAME,
    TRY_CAST(SPLIT_PART(GEO_POINT_2D, ',', 1) AS FLOAT) AS CENTROID_LAT,
    TRY_CAST(SPLIT_PART(GEO_POINT_2D, ',', 2) AS FLOAT) AS CENTROID_LON,
    ST_ASWKT(TRY_TO_GEOGRAPHY(GEO_SHAPE)) AS GEOMETRY_WKT
FROM PARIS_IMMO.RAW.RENT_RAW
WHERE CODE_GRAND_QUARTIER IS NOT NULL
  AND NOM_QUARTIER IS NOT NULL;


-- DIM_CONSTRUCTION_PERIOD
TRUNCATE TABLE PARIS_IMMO.NORMALIZED.DIM_CONSTRUCTION_PERIOD;
INSERT INTO PARIS_IMMO.NORMALIZED.DIM_CONSTRUCTION_PERIOD
SELECT
    ROW_NUMBER() OVER (ORDER BY CONSTRUCTION_PERIOD) AS CONSTRUCTION_PERIOD_ID,
    CONSTRUCTION_PERIOD
FROM (
    SELECT DISTINCT
        EPOQUE_CONSTRUCTION AS CONSTRUCTION_PERIOD
    FROM PARIS_IMMO.RAW.RENT_RAW
    WHERE EPOQUE_CONSTRUCTION IS NOT NULL
);


-- DIM_FURNISHED_STATUS
TRUNCATE TABLE PARIS_IMMO.NORMALIZED.DIM_FURNISHED_STATUS;
INSERT INTO PARIS_IMMO.NORMALIZED.DIM_FURNISHED_STATUS
SELECT
    ROW_NUMBER() OVER (ORDER BY FURNISHED_STATUS) AS FURNISHED_STATUS_ID,
    FURNISHED_STATUS
FROM (
    SELECT DISTINCT
        CASE
            WHEN LOWER(TYPE_LOCATION) = 'meublé' THEN 'FURNISHED'
            WHEN LOWER(TYPE_LOCATION) = 'non meublé' THEN 'UNFURNISHED'
            ELSE TYPE_LOCATION
        END AS FURNISHED_STATUS
    FROM PARIS_IMMO.RAW.RENT_RAW
    WHERE TYPE_LOCATION IS NOT NULL
);

