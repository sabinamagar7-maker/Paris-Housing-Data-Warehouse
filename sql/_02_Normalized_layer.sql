TRUNCATE TABLE PARIS_IMMO.NORMALIZED.FACT_HOUSING_PERMIT;

INSERT INTO PARIS_IMMO.NORMALIZED.FACT_HOUSING_PERMIT
    (PERMIT_ID,
     AUTHORIZATION_DATE,
     ARRONDISSEMENT_CODE,
     YEAR,
     PERMIT_TYPE,
     PROJECT_TYPE,
     HOUSING_UNITS_CREATED,
     SURFACE_CREATED)
WITH CLEANED AS (
    SELECT
        NUM_DAU AS PERMIT_ID,
        TRY_TO_DATE(DATE_REELLE_AUTORISATION) AS AUTHORIZATION_DATE,
        TYPE_DAU AS PERMIT_TYPE,
        COALESCE(NATURE_PROJET_COMPLETEE, '0') AS PROJECT_TYPE,
        TRY_CAST(NB_LGT_TOT_CREES AS INT) AS HOUSING_UNITS_CREATED,
        TRY_CAST(SURF_HAB_CREEE AS FLOAT) AS SURFACE_CREATED,
        CASE
            WHEN LEFT(ADR_CODPOST_TER, 2) = '75'
             AND LENGTH(ADR_CODPOST_TER) = 5
            THEN TRY_CAST('751' || LPAD(RIGHT(ADR_CODPOST_TER, 2), 2, '0') AS INT)
        END AS ARRONDISSEMENT_CODE,
        YEAR(TRY_TO_DATE(DATE_REELLE_AUTORISATION)) AS YR
    FROM PARIS_IMMO.RAW.HOUSING_RAW
    WHERE DEP_CODE = '75'
      AND NUM_DAU IS NOT NULL
),
DEDUPED AS (
    SELECT *,
        ROW_NUMBER() OVER (
            PARTITION BY PERMIT_ID
            ORDER BY AUTHORIZATION_DATE DESC NULLS LAST
        ) AS RN
    FROM CLEANED
    WHERE ARRONDISSEMENT_CODE BETWEEN 75101 AND 75120
      AND YR BETWEEN 2020 AND 2025
)
SELECT
    PERMIT_ID,
    AUTHORIZATION_DATE,
    ARRONDISSEMENT_CODE,
    YR,
    PERMIT_TYPE,
    PROJECT_TYPE,
    HOUSING_UNITS_CREATED,
    SURFACE_CREATED
FROM DEDUPED
WHERE RN = 1;


