-- FACT_COMPANY_ACTIVITY
TRUNCATE TABLE PARIS_IMMO.NORMALIZED.FACT_COMPANY_ACTIVITY;
INSERT INTO PARIS_IMMO.NORMALIZED.FACT_COMPANY_ACTIVITY
    (ESTABLISHMENT_ID, ESTABLISHMENT_CREATION_DATE, ARRONDISSEMENT_CODE,
     MAIN_ACTIVITY_CODE, ADMINISTRATIVE_STATUS, EMPLOYEE_SIZE_BRACKET,
     YEAR, YEAR_CLOSED)
WITH cleaned AS (
    SELECT
        siret AS establishment_id,
        TRY_TO_DATE(dateCreationEtablissement) AS establishment_creation_date,
        CASE
            WHEN LEFT(codePostalEtablissement, 2) = '75'
             AND LENGTH(codePostalEtablissement) = 5
            THEN TRY_CAST('751' || LPAD(RIGHT(codePostalEtablissement,2),2,'0') AS INT)
        END AS arrondissement_code,
        ACTIVITEPRINCIPALE_ETABLISSEMENT AS main_activity_code,
        CASE etatAdministratifEtablissement
             WHEN 'A' THEN 'Active'
             WHEN 'F' THEN 'Closed'
             ELSE etatAdministratifEtablissement
        END AS administrative_status,
        trancheEffectifsEtablissement AS employee_size_bracket,
        YEAR(TRY_TO_DATE(dateCreationEtablissement)) AS yr,
        CASE WHEN etatAdministratifEtablissement = 'F'
             THEN YEAR(TRY_TO_DATE(dateDernierTraitementEtablissement))
        END AS year_closed
    FROM PARIS_IMMO.RAW.COMPANY_RAW
    WHERE siret IS NOT NULL
)
SELECT
    establishment_id, establishment_creation_date, arrondissement_code,
    main_activity_code, administrative_status, employee_size_bracket,
    yr, year_closed
FROM cleaned
WHERE arrondissement_code IS NOT NULL
  AND main_activity_code IS NOT NULL
  AND main_activity_code IN (SELECT MAIN_ACTIVITY_CODE FROM PARIS_IMMO.NORMALIZED.DIM_ACTIVITY)
  AND arrondissement_code BETWEEN 75101 AND 75120
  AND yr BETWEEN 2020 AND 2025
QUALIFY ROW_NUMBER() OVER (PARTITION BY establishment_id
                            ORDER BY establishment_creation_date DESC) = 1;

